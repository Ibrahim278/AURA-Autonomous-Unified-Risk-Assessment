import { useEffect, useState } from 'react'
import { api } from '../api.js'
import ForecastPanel from './ForecastPanel.jsx'

export default function AIPanel({ crewId, member, day, live, catalog, onSelectIndicator, forecast, onAsk }) {
  const [aiInfo, setAiInfo] = useState(null)
  const [briefing, setBriefing] = useState(null)
  const [loadingBrief, setLoadingBrief] = useState(false)
  const [error, setError] = useState(null)

  useEffect(() => {
    api.aiStatus().then(setAiInfo).catch(() => setAiInfo({ enabled: false }))
  }, [])

  const requestedDay = live ? null : day

  const loadBriefing = async () => {
    setLoadingBrief(true)
    setError(null)
    try {
      setBriefing(await api.briefing(crewId, requestedDay))
    } catch (e) {
      setError(e.message)
    } finally {
      setLoadingBrief(false)
    }
  }

  const b = briefing?.briefing

  return (
    <section className="panel ai-panel">
      <div className="panel-head">
        <h2>✦ AI flight surgeon</h2>
        {aiInfo && (
          <span className={`pill ai-mode ${aiInfo.enabled ? 'on' : 'off'}`}>
            {aiInfo.enabled ? `Claude · ${aiInfo.model}` : 'Rule-based mode (no Claude login)'}
          </span>
        )}
      </div>

      <div className="ai-grid">
        <div className="briefing">
          {!b && (
            <div className="briefing-empty">
              <p>
                Get a plain-language summary of {member.name}&apos;s health on day {day}: what
                matters most, how the indicators connect, and what to do next.
              </p>
              <button className="primary" onClick={loadBriefing} disabled={loadingBrief}>
                {loadingBrief ? 'Analysing telemetry…' : 'Generate daily briefing'}
              </button>
            </div>
          )}
          {b && (
            <>
              {b.escalate && <div className="escalate">📡 Contact the flight surgeon now.</div>}
              <p className="headline">{b.headline}</p>
              <ol className="priorities">
                {b.priorities.map((p) => (
                  <li key={p.title}>
                    <strong>{p.title}</strong>
                    <p>{p.detail}</p>
                    <p className="action">→ {p.action}</p>
                    <div className="hazards">
                      {p.indicators.filter((k) => catalog[k]).map((k) => (
                        <button key={k} className="tag link-tag" onClick={() => onSelectIndicator(k)}>
                          {catalog[k].name}
                        </button>
                      ))}
                    </div>
                  </li>
                ))}
              </ol>
              {b.patterns.length > 0 && (
                <>
                  <h3>Patterns AURA noticed</h3>
                  <ul>{b.patterns.map((x) => <li key={x}>{x}</li>)}</ul>
                </>
              )}
              <p className="encourage">{b.encouragement}</p>
              <p className="hint">Want the reasoning? <button className="link" onClick={onAsk}>Ask AURA</button>, for example &quot;Are any of my indicators connected?&quot;</p>
              <div className="briefing-foot">
                <span className="muted">
                  {briefing.mode === 'ai' ? `Generated by ${briefing.model}` : briefing.note}
                </span>
                <button className="link" onClick={loadBriefing} disabled={loadingBrief}>
                  {loadingBrief ? 'Refreshing…' : '↻ Refresh'}
                </button>
              </div>
            </>
          )}
        </div>

        <ForecastPanel forecast={forecast} onSelectIndicator={onSelectIndicator} />
      </div>
      {error && <div className="toast error">{error}</div>}
      <p className="hint">
        The AI explains and coaches, and the forecast is a trend, not a prediction. Alert levels always
        come from AURA&apos;s rule engine, and it never replaces the ground medical team. Questions?
        Use ✦ Ask AURA (bottom right).
      </p>
    </section>
  )
}
