import { useEffect, useRef, useState } from 'react'
import { api } from '../api.js'

const SUGGESTIONS = [
  'What should I focus on today?',
  'Why is my status what it is?',
  'Are any of my indicators connected?',
  'When should I call the flight surgeon?',
]

export default function AIPanel({ crewId, member, day, live, catalog, onSelectIndicator }) {
  const [aiInfo, setAiInfo] = useState(null)
  const [briefing, setBriefing] = useState(null)
  const [loadingBrief, setLoadingBrief] = useState(false)
  const [chat, setChat] = useState([])
  const [question, setQuestion] = useState('')
  const [asking, setAsking] = useState(false)
  const [error, setError] = useState(null)
  const chatEnd = useRef(null)

  useEffect(() => {
    api.aiStatus().then(setAiInfo).catch(() => setAiInfo({ enabled: false }))
  }, [])

  useEffect(() => {
    chatEnd.current?.scrollIntoView({ behavior: 'smooth', block: 'nearest' })
  }, [chat])

  const requestedDay = live ? null : day

  const loadBriefing = async () => {
    setLoadingBrief(true)
    setError(null)
    try {
      setBriefing(await api.briefing(crewId, requestedDay))
    } catch (e) {
      setError(e.message)
    } finally {
      setLoadingBrief(false)
    }
  }

  const send = async (text) => {
    const q = (text ?? question).trim()
    if (!q || asking) return
    const history = chat.map(({ role, content }) => ({ role, content }))
    setChat([...chat, { role: 'user', content: q }])
    setQuestion('')
    setAsking(true)
    setError(null)
    try {
      const r = await api.ask(crewId, { question: q, history, day: requestedDay })
      setChat((c) => [...c, { role: 'assistant', content: r.answer, mode: r.mode }])
    } catch (e) {
      setError(e.message)
    } finally {
      setAsking(false)
    }
  }

  const b = briefing?.briefing
  const firstName = member.name.split(' ').slice(-2, -1)[0] ?? member.name

  return (
    <section className="panel ai-panel">
      <div className="panel-head">
        <h2>✦ AI flight surgeon</h2>
        {aiInfo && (
          <span className={`pill ai-mode ${aiInfo.enabled ? 'on' : 'off'}`}>
            {aiInfo.enabled ? `Claude · ${aiInfo.model}` : 'Rule-based mode (no Claude login)'}
          </span>
        )}
      </div>

      <div className="ai-grid">
        <div className="briefing">
          {!b && (
            <div className="briefing-empty">
              <p>
                Get a plain-language summary of {member.name}&apos;s health on day {day}: what
                matters most, how the indicators connect, and what to do next.
              </p>
              <button className="primary" onClick={loadBriefing} disabled={loadingBrief}>
                {loadingBrief ? 'Analysing telemetry…' : 'Generate daily briefing'}
              </button>
            </div>
          )}
          {b && (
            <>
              {b.escalate && <div className="escalate">📡 Contact the flight surgeon now.</div>}
              <p className="headline">{b.headline}</p>
              <ol className="priorities">
                {b.priorities.map((p) => (
                  <li key={p.title}>
                    <strong>{p.title}</strong>
                    <p>{p.detail}</p>
                    <p className="action">→ {p.action}</p>
                    <div className="hazards">
                      {p.indicators.filter((k) => catalog[k]).map((k) => (
                        <button key={k} className="tag link-tag" onClick={() => onSelectIndicator(k)}>
                          {catalog[k].name}
                        </button>
                      ))}
                    </div>
                  </li>
                ))}
              </ol>
              {b.patterns.length > 0 && (
                <>
                  <h3>Patterns AURA noticed</h3>
                  <ul>{b.patterns.map((x) => <li key={x}>{x}</li>)}</ul>
                </>
              )}
              <p className="encourage">{b.encouragement}</p>
              <div className="briefing-foot">
                <span className="muted">
                  {briefing.mode === 'ai' ? `Generated by ${briefing.model}` : briefing.note}
                </span>
                <button className="link" onClick={loadBriefing} disabled={loadingBrief}>
                  {loadingBrief ? 'Refreshing…' : '↻ Refresh'}
                </button>
              </div>
            </>
          )}
        </div>

        <div className="chat">
          <div className="chat-log" aria-live="polite">
            {chat.length === 0 && (
              <p className="muted">Ask about {firstName}&apos;s data. Answers use only the telemetry shown here.</p>
            )}
            {chat.map((m, i) => (
              <div key={i} className={`bubble ${m.role}`}>{m.content}</div>
            ))}
            {asking && <div className="bubble assistant typing">…</div>}
            <div ref={chatEnd} />
          </div>
          <div className="suggestions">
            {SUGGESTIONS.map((s) => (
              <button key={s} className="chip" onClick={() => send(s)} disabled={asking}>{s}</button>
            ))}
          </div>
          <form className="chat-input" onSubmit={(e) => { e.preventDefault(); send() }}>
            <input
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              placeholder="Ask the flight surgeon…"
              maxLength={2000}
            />
            <button className="primary" disabled={asking || !question.trim()}>Send</button>
          </form>
        </div>
      </div>
      {error && <div className="toast error">{error}</div>}
      <p className="hint">
        The AI explains and coaches. Alert levels always come from AURA&apos;s rule engine, and it
        never replaces the ground medical team.
      </p>
    </section>
  )
}
