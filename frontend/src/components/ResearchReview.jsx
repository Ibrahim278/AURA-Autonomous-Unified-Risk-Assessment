import { useEffect, useState } from 'react'
import { api } from '../api.js'

const CONCERN = { high: 'critical', moderate: 'warning', low: 'normal' }

export default function ResearchReview({ crew, colors, onSelectMarker, focusCrew }) {
  const [who, setWho] = useState(crew[0])
  const [result, setResult] = useState({})
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState(null)

  useEffect(() => setError(null), [who])
  useEffect(() => {
    if (focusCrew && crew.includes(focusCrew)) setWho(focusCrew)
  }, [focusCrew, crew])

  const run = async () => {
    setLoading(true)
    setError(null)
    try {
      const r = await api.researchReview(who)
      setResult((prev) => ({ ...prev, [who]: r }))
    } catch (e) {
      setError(e.message)
    } finally {
      setLoading(false)
    }
  }

  const r = result[who]
  const rv = r?.review

  return (
    <div className="research-review" id="research-review">
      <div className="panel-head">
        <h3>✦ AI review of real crew bloodwork</h3>
        <div className="seg">
          {crew.map((c) => (
            <button key={c} className={c === who ? 'active' : ''} onClick={() => setWho(c)}>
              <i className="sw" style={{ background: colors[c] }} /> {c}
            </button>
          ))}
        </div>
      </div>

      {!rv && (
        <div className="briefing-empty">
          <p className="muted">
            Claude compares {who}&apos;s metabolic panel and blood count to their own preflight baseline
            and the lab ranges, then suggests what AURA would monitor on a future flight.
          </p>
          <button className="primary" onClick={run} disabled={loading}>
            {loading ? `Reviewing ${who}'s labs…` : `Review ${who}`}
          </button>
        </div>
      )}
      {error && <p className="muted">{error}</p>}

      {rv && (
        <>
          <p className="headline">{rv.headline}</p>
          <div className="review-grid">
            <div>
              <h4>Findings</h4>
              <ul className="findings">
                {rv.findings.map((f) => (
                  <li key={f.marker} style={{ '--lvl': `var(--${CONCERN[f.concern]})` }}>
                    <button className="link marker" onClick={() => onSelectMarker(f.marker)}>{f.marker}</button>
                    <span className="concern">{f.concern}</span>
                    <p>{f.observation}</p>
                    <p className="muted">{f.interpretation}</p>
                  </li>
                ))}
              </ul>
            </div>
            <div>
              <h4>Recommendations</h4>
              <ol className="priorities">
                {rv.recommendations.map((x) => (
                  <li key={x.action}><strong>{x.action}</strong><p className="muted">{x.rationale}</p></li>
                ))}
              </ol>
              {rv.data_caveats.length > 0 && (
                <>
                  <h4>Data caveats</h4>
                  <ul className="caveats">{rv.data_caveats.map((c) => <li key={c}>{c}</li>)}</ul>
                </>
              )}
            </div>
          </div>
          <div className="briefing-foot">
            <span className="muted">{r.mode === 'ai' ? `Generated by ${r.model} from real OSDR data. Not medical advice.` : r.note}</span>
            <button className="link" onClick={run} disabled={loading}>{loading ? 'Reviewing…' : 'Regenerate'}</button>
          </div>
        </>
      )}
    </div>
  )
}
